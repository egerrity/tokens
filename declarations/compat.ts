// each with how the bridge in a theme file treats it. `alias` emits the name as a
// reference to the token; `codemod` emits nothing, because the uses split by property
// and the code-side rewrite settles each one; `skip` emits nothing, because no code
// reads the name; `exclude` is a value set at run time, not a token; `app` is the app's
// own literal, not a token of the set. A shade (`-dark`, `-light` and their degrees)
